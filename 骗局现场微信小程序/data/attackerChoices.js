// 仅这些游戏目标对应虚拟资金支出；数值由游戏设定，并非原案损失。
const paymentStages = { 1: [2], 2: [2], 3: [2], 7: [2], 8: [2], 11: [2], 15: [2], 16: [0, 2], 17: [2], 20: [2], 22: [2], 26: [2], 28: [2], 29: [2], 30: [2] }
function makeAttackerStages(id, originalStages) {
  const goals = objectives[id]
  if (!goals || !originalStages || goals.length !== originalStages.length) return []
  return originalStages.map((stage, index) => {
    const [advance, delay] = goals[index]
    const safe = stage.choices.find(choice => choice.correct)
    if (!safe) throw new Error(`case ${id} stage ${index}: missing safe action`)
    const choices = [
      { label: advance, effect: 'advance', correct: false, virtualPayment: (paymentStages[id] || []).includes(index), note: `你选择“${advance}”。这是模拟引导目标；接下来观察当事人是否独立核验。` },
      { label: delay, effect: 'delay', correct: false, note: `你选择“${delay}”。当前尚未完成独立核验，需要继续观察当事人的反应。` },
      { label: `停止引导：${perspectives[id].focus[index]}`, effect: 'stop', correct: true, note: safe.note }
    ]
    const shift = (id + index) % choices.length
    return { ...stage, prompt: '作为游戏中的引导者，你选择如何影响当前情境？', choices: choices.slice(shift).concat(choices.slice(0, shift)) }
  })
}
module.exports = { makeAttackerStages }
