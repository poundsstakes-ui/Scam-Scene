function getEpisode(id) {
  const stages = episodes[id]
  if (!stages) return null
  return stages.map(([title, clue, prompt, safe, note], index) => {
    const choices = [
      { label: safe, correct: true, note },
      { label: '仅依据当前联系人提供的信息继续判断', correct: false, note },
      { label: '暂不核实，继续等待对方的安排', correct: false, note }
    ]
    const shift = index % choices.length
    return { title, clue, prompt, dialogue: dialogues[id] ? dialogues[id][index] : '', choices: choices.slice(shift).concat(choices.slice(0, shift)) }
  })
}
for (const id of Object.keys(episodes)) {
  if (!reviewTopics[id]) reviewTopics[id] = episodes[id].map(stage => stage[0]).join('、')
}
